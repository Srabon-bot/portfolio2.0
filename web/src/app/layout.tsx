/*
 * Root layout — wraps every page on the site.
 *
 * `next/font/google` downloads Roboto at build time and injects it as a
 * CSS variable, so there is no layout shift and no Google Fonts request
 * at runtime (better privacy and performance).
 */
import type { Metadata } from "next";
import { Roboto } from "next/font/google";
import "./globals.css";

/* Load Roboto with the four weights the PRD requires */
const roboto = Roboto({
  subsets: ["latin"],
  weight: ["400", "500", "700", "900"],
  variable: "--font-roboto",   /* becomes a CSS custom property */
  display: "swap",             /* show fallback font while Roboto loads */
});

/* Default SEO metadata — individual pages can override these */
export const metadata: Metadata = {
  title: {
    default: "Srabon — Full-Stack Developer",
    template: "%s | Srabon",   /* e.g. "About | Srabon" on other pages */
  },
  description:
    "Full-stack developer (MERN · Next.js · TypeScript) building web apps that solve real problems for people in Bangladesh.",
  openGraph: {
    type: "website",
    locale: "en_US",
    url: process.env.NEXT_PUBLIC_SITE_URL ?? "https://srabon.dev",
    siteName: "Srabon's Portfolio",
  },
  robots: {
    index: true,
    follow: true,
  },
};

/* LayoutProps is generated by Next.js from the route structure */
export default function RootLayout({ children }: LayoutProps<"/">) {
  return (
    <html
      lang="en"
      /* Apply the Roboto CSS variable to <html> so every element inherits it */
      className={`${roboto.variable}`}
    >
      <body>
        {children}
      </body>
    </html>
  );
}
